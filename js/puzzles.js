const DIFFICULTIES = ['初級', '中級', '上級'];

function getDayIndex() {
  const start = new Date('2025-01-01');
  return Math.floor((new Date() - start) / (1000 * 60 * 60 * 24));
}

function getPuzzleByDifficulty(difficulty) {
  const pool = PUZZLES.filter(p => p.difficulty === difficulty);
  if (pool.length === 0) return null;
  return pool[getDayIndex() % pool.length];
}

function getPuzzleForToday() {
  return PUZZLES[getDayIndex() % PUZZLES.length];
}

function getPuzzleById(id) {
  return PUZZLES.find(p => p.id === id) || PUZZLES[0];
}
